CREATE TABLE IF NOT EXISTS public.orders (
  id text PRIMARY KEY,
  tracking_token_hash text NOT NULL UNIQUE,
  service_id text NOT NULL,
  customer_name text NOT NULL,
  customer_phone text NOT NULL,
  description text NOT NULL,
  status text NOT NULL,
  progress integer NOT NULL,
  estimated_completion timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS public.order_status_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id text NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS public.order_attachments (
  id uuid PRIMARY KEY,
  order_id text NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  storage_name text NOT NULL UNIQUE,
  original_name text NOT NULL,
  mime_type text NOT NULL,
  size integer NOT NULL
);

CREATE TABLE IF NOT EXISTS public.pending_uploads (
  id uuid PRIMARY KEY,
  storage_name text NOT NULL UNIQUE,
  original_name text NOT NULL,
  mime_type text NOT NULL,
  size integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS order_status_history_order_id
  ON public.order_status_history(order_id, id);
CREATE INDEX IF NOT EXISTS orders_created_at
  ON public.orders(created_at DESC);

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_status_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pending_uploads ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.orders, public.order_status_history, public.order_attachments,
  public.pending_uploads FROM anon, authenticated;
GRANT ALL ON public.orders, public.order_status_history, public.order_attachments,
  public.pending_uploads TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.order_status_history_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.create_service_order(p_order jsonb, p_attachments jsonb, p_upload_ids uuid[])
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_order_id text := p_order->>'id';
BEGIN
  INSERT INTO public.orders (
    id, tracking_token_hash, service_id, customer_name, customer_phone, description,
    status, progress, estimated_completion, created_at, updated_at
  ) VALUES (
    v_order_id, p_order->>'tracking_token_hash', p_order->>'service_id',
    p_order->>'customer_name', p_order->>'customer_phone', p_order->>'description',
    p_order->>'status', (p_order->>'progress')::integer,
    (p_order->>'estimated_completion')::timestamptz,
    (p_order->>'created_at')::timestamptz, (p_order->>'updated_at')::timestamptz
  );

  INSERT INTO public.order_status_history (order_id, status, note, created_at)
  VALUES (v_order_id, p_order->>'status', '', (p_order->>'created_at')::timestamptz);

  INSERT INTO public.order_attachments (id, order_id, storage_name, original_name, mime_type, size)
  SELECT item.id, v_order_id, item.storage_name, item.original_name, item.mime_type, item.size
  FROM jsonb_to_recordset(p_attachments) AS item(
    id uuid, storage_name text, original_name text, mime_type text, size integer
  );

  DELETE FROM public.pending_uploads WHERE id = ANY(p_upload_ids);
END;
$$;

CREATE OR REPLACE FUNCTION public.update_service_order(
  p_order_id text,
  p_status text,
  p_progress integer,
  p_estimated_completion timestamptz,
  p_note text,
  p_updated_at timestamptz
)
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  UPDATE public.orders
  SET status = p_status,
      progress = p_progress,
      estimated_completion = p_estimated_completion,
      updated_at = p_updated_at
  WHERE id = p_order_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order not found' USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO public.order_status_history (order_id, status, note, created_at)
  VALUES (p_order_id, p_status, p_note, p_updated_at);
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_order_status_history_sequence()
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM setval(
    pg_get_serial_sequence('public.order_status_history', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
  )
  FROM public.order_status_history;
END;
$$;

REVOKE ALL ON FUNCTION public.create_service_order(jsonb, jsonb, uuid[]) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.update_service_order(text, text, integer, timestamptz, text, timestamptz) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.sync_order_status_history_sequence() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_service_order(jsonb, jsonb, uuid[]) TO service_role;
GRANT EXECUTE ON FUNCTION public.update_service_order(text, text, integer, timestamptz, text, timestamptz) TO service_role;
GRANT EXECUTE ON FUNCTION public.sync_order_status_history_sequence() TO service_role;

